--
-- ЧТО УДАЛЯЕТСЯ
--   * учётные записи (auth.users) — вместе с ними профили, сессии, identities;
--   * цели, квесты, дружбы, голоса за пресеты;
--   * пользовательские пресеты (системные 'sys\_%' остаются);
--   * сессии фокуса, использования промокодов, награды и сезоны лиг.
--
-- ЧТО ОСТАЁТСЯ
--   * промокоды (promo_codes) — это контент для игроков;
--   * системные пресеты goal_presets с id 'sys\_%' — без них не работает
--     голосование за пресеты;
--   * конфигурация: league_tiers, league_rewards, era_config,
--     camp_building_effects, goal_slot_prices;
--   * сама схема, функции, политики и триггеры.
--
-- ПОРЯДОК РАБОТЫ
--   1. Сделайте копию, если она нужна: Supabase → Database → Backups, либо
--      выгрузите нужные таблицы в CSV через Table Editor.
--   2. Выполните блок «ДО» — он покажет, что именно будет удалено.
--   3. Выполните удаления. Каждый оператор самостоятелен: если один упадёт
--      из-за внешнего ключа, остальные всё равно можно выполнить, а повторный
--      запуск безопасен (удаление идемпотентно). Если упадёт — пришлите текст
--      ошибки: в нём будет названа таблица, которую надо очистить раньше.
--   4. Выполните блок «ПОСЛЕ» — он должен показать нули везде, кроме
--      promo_codes и системных пресетов.
--
-- ВАЖНО ПРО SQL EDITOR: при ошибке внутри пакета редактор прерывает выполнение
-- и НЕ откатывает уже сделанное. Поэтому запускайте блоками, а не одним куском.
-- ============================================================================


-- ---------------------------------------------------------------------------
-- 1. ДО: что есть в базе прямо сейчас
-- ---------------------------------------------------------------------------
-- Считает строки во всех таблицах схемы public, включая те, о которых
-- в проекте нет миграций. Так видно и результат очистки.

select table_name,
       (xpath('/row/cnt/text()',
              query_to_xml(format('select count(*) as cnt from public.%I', table_name),
                           false, true, '')))[1]::text::int as rows
from information_schema.tables
where table_schema = 'public'
  and table_type = 'BASE TABLE'
order by rows desc, table_name;


-- ---------------------------------------------------------------------------
-- 2. Игровые данные
-- ---------------------------------------------------------------------------

-- 2.1 Голоса за пресеты (ссылаются на пресеты и на игроков)
delete from public.preset_votes;

-- 2.2 Использования промокодов (сами коды остаются)
delete from public.promo_redemptions;

-- 2.3 Серверные сессии фокуса
delete from public.focus_sessions;

-- 2.4 Квесты, затем цели: квесты ссылаются на цели
delete from public.quests;
delete from public.goals;

-- 2.5 Дружбы
delete from public.friendships;

-- 2.6 Пользовательские пресеты. Системные (id вида 'sys_...') остаются на
--     месте: на них ссылается голосование и таблица пресетов в приложении.
delete from public.goal_presets
where coalesce(id, '') not like 'sys\_%';


-- ---------------------------------------------------------------------------
-- 3. Лиги: тестовые сезоны и награды
-- ---------------------------------------------------------------------------
-- Награды ссылаются на сезоны. После очистки первый же заход в приложение
-- создаст новый сезон на 7 дней (open_league_season вызывается автоматически).

delete from public.league_awards;
delete from public.league_seasons;


-- ---------------------------------------------------------------------------
-- 4. Профили и учётные записи
-- ---------------------------------------------------------------------------
-- Профили удаляем до учётных записей: если внешний ключ на auth.users объявлен
-- без ON DELETE CASCADE, удаление пользователей упало бы, и профили остались
-- бы висеть без владельца.

delete from public.profiles;

-- Учётные записи. Вместе с ними уходят identities и сессии: приложение на
-- телефоне потеряет вход и покажет экран регистрации — это ожидаемо.
--
-- Альтернатива: то же самое сделать мышкой в Supabase → Authentication → Users
-- (отметить всех и удалить). Способ на выбор.
delete from auth.users;


-- ---------------------------------------------------------------------------
-- 5. ПОСЛЕ: проверка
-- ---------------------------------------------------------------------------
-- Повторите запрос из блока 1. Ожидаемо:
--   * rows = 0 у profiles, goals, quests, friendships, preset_votes,
--     promo_redemptions, focus_sessions, league_seasons, league_awards;
--   * rows > 0 только у promo_codes, league_tiers, league_rewards, era_config,
--     camp_building_effects, goal_slot_prices и системных goal_presets.
-- Если какая-то таблица осталась с данными и её нет в списке выше — пришлите
-- её имя, добавим удаление.

select table_name,
       (xpath('/row/cnt/text()',
              query_to_xml(format('select count(*) as cnt from public.%I', table_name),
                           false, true, '')))[1]::text::int as rows
from information_schema.tables
where table_schema = 'public'
  and table_type = 'BASE TABLE'
order by rows desc, table_name;


-- ---------------------------------------------------------------------------
-- 6. Что проверить в приложении после очистки
-- ---------------------------------------------------------------------------
-- 1. Регистрация нового игрока проходит, и профиль создаётся автоматически
--    (в приложении нет создания профиля: это делает триггер на auth.users).
--    Если после регистрации приложение показывает ошибку загрузки — значит
--    триггер не сработал, и это надо чинить до релиза.
-- 2. Промокод PRAXIS2026 принимается новым аккаунтом один раз.
-- 3. Вкладка «Рейтинг»: игрок один, он же первый в Бронзовой лиге, награда
